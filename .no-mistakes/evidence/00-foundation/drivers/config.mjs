import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {parse} from 'yaml';
const gate=parse(readFileSync('.no-mistakes.yaml','utf8'));
const workflow=parse(readFileSync('.github/workflows/ci.yml','utf8'));
const job=workflow.jobs['required-checks'];
const cache=job.steps.find(step=>step.uses?.startsWith('actions/cache@'));
const mise=job.steps.find(step=>step.uses?.startsWith('jdx/mise-action@'));
const lock=JSON.parse(readFileSync('package-lock.json','utf8'));
const clerkPackages=Object.keys(lock.packages).filter(name=>name.includes('/@clerk/'));
assert.equal(gate.commit,undefined);
assert.ok(Object.values(gate.auto_fix).every(value=>value===0));
assert.deepEqual(clerkPackages,[]);
assert.equal(mise.with.install,false); assert.equal(mise.with.cache,false);
assert.equal(cache.with.key,"mise-${{ runner.os }}-${{ hashFiles('mise.lock') }}");
assert.ok(job.steps.findIndex(step=>step.run==='mise install')>job.steps.indexOf(mise));
const result={autoFix:gate.auto_fix,commitSetting:gate.commit??null,protectedPaths:gate.protected_paths,cache:cache.with,mise:mise.with,installCommand:'mise install',clerkPackages};
writeFileSync('/Users/moeghashim/.no-mistakes/evidence/01M6A41GP1MDXJ1Q12SBYVHE25/configuration.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
