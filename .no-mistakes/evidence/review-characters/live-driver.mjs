import { Miniflare, convertV4MiniflareOptions } from 'miniflare';
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
const evidence = '/Users/moeghashim/.no-mistakes/evidence/01M6GJ6EM8RT10PF88QQ04ERZS';
const logs=[];
const options = convertV4MiniflareOptions({ name:'landing-live-test', modules:true, scriptPath:'apps/landing/src/index.js', compatibilityDate:'2026-10-01', host:'127.0.0.1', port:0, assets:{directory:'apps/landing/public',binding:'ASSETS',run_worker_first:true,assetConfig:{html_handling:'none',not_found_handling:'none'}}, });
options.workers[0].config.assets.hasUserWorker=true;
options.workers[0].config.exports={default:{type:'worker'}};
const mf=new Miniflare(options);
let browser;
try {
const base=(await mf.ready).origin;
browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror', e=>errors.push(e.message));
const initial=await page.goto(base+'/review/'); console.log('INITIAL',initial.status(),page.url(),(await page.locator('body').innerText()).slice(0,1200));
await page.locator('a[href="/review/characters"]').click();
await page.waitForURL('**/review/characters');
await page.getByRole('heading',{name:'Squadmates',exact:true}).waitFor();
assert.equal(await page.locator('.cast .mate').count(),9);
assert.deepEqual(await page.locator('.cast .mate b').allTextContents(),['Ten','Dash','Juno','Pop','Penny','Stack','Scout','Brick','Lens']);
await page.screenshot({path:evidence+'/characters-desktop.png',fullPage:true});
logs.push({scenario:'Review index opens complete nine-character proposal',url:page.url(),characters:await page.locator('.cast .mate b').allTextContents(),proposal:await page.locator('p.note').nth(1).innerText()});
assert.equal(await page.locator('.states tbody tr').count(),4);
assert.equal(await page.locator('.states svg[role="img"]').count(),27);
assert.equal(await page.locator('.list .row').count(),7);
assert.deepEqual(await page.locator('.sizes svg').evaluateAll(xs=>xs.map(x=>x.getAttribute('width'))),['16','24','32','48','96']);
const stateLabels=await page.locator('.states th').allTextContents();
assert.equal(stateLabels.length,10);
logs.push({scenario:'All nine states, seven sample list rows and five avatar sizes render',stateLabels,accessibleSample:await page.locator('.states svg').first().getAttribute('aria-label')});
const blink=page.locator('.cast .sm-blink').first();
assert.equal(await blink.evaluate(e=>getComputedStyle(e).animationName),'sm-blink');
await page.emulateMedia({reducedMotion:'reduce'});
assert.equal(await blink.evaluate(e=>getComputedStyle(e).animationName),'none');
logs.push({scenario:'Reduced motion disables blinking',normal:'sm-blink',reduced:'none'});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:evidence+'/characters-mobile.png',fullPage:true});
const dimensions=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth,table:document.querySelector('.states').scrollWidth,tableBox:document.querySelector('.states').clientWidth}));
assert.ok(dimensions.document<=390,JSON.stringify(dimensions));
assert.ok(dimensions.table>dimensions.tableBox);
await page.locator('.states').hover();
await page.mouse.wheel(1000,0);
await page.waitForTimeout(200);
assert.ok(await page.locator('.states').evaluate(e=>e.scrollLeft)>0);
await page.locator('.states').screenshot({path:evidence+'/states-mobile-scrolled.png'});
logs.push({scenario:'390px layout has no page overflow and states scroll to Dropped',...dimensions,scrollLeft:await page.locator('.states').evaluate(e=>e.scrollLeft)});
await page.getByRole('link',{name:'Back to review'}).click();
assert.equal(new URL(page.url()).pathname,'/review/');
const response=await page.goto(base+'/review/characters');
assert.equal(response.status(),200);
const headers=response.headers();
assert.equal(headers['x-robots-tag'],'noindex, nofollow');
assert.equal(headers['cache-control'],'no-cache');
await page.getByRole('heading',{name:'Squadmates',exact:true}).waitFor();
logs.push({scenario:'Back link and direct URL work without sign-in; review indexing headers retained',status:response.status(),headers});
await page.goto(base+'/');
assert.equal(await page.getByRole('heading',{name:'Hire a squad of AI agents to run your business'}).count(),1);
assert.equal(await page.locator('.cast').count(),0);
await page.screenshot({path:evidence+'/holding-page.png',fullPage:true});
assert.deepEqual(errors,[]);
logs.push({scenario:'Proposal stays off holding page',heading:await page.locator('h1').innerText(),pageErrors:errors});
} finally {
writeFileSync(evidence+'/live-results.json',JSON.stringify(logs,null,2));
await browser?.close();await mf.dispose();
}
console.log(JSON.stringify(logs,null,2));
