import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {createRepositories, schema, saveWorkspace} from '@tensquads/adapters';
import {Kernel} from '@tensquads/kernel';
import {eq, and} from 'drizzle-orm';
import {openPglite} from '../packages/adapters/test/pglite.ts';
import {replaceDemoAccount} from '../packages/seed/src/demo-account.ts';
import {workspaceFromDesign} from '../packages/seed/src/workspace.ts';
import {readOverview} from '../apps/web/src/server/overview-read.ts';

const opened = await openPglite();
const {db} = opened;
const scope = {accountId:'local-overview',mode:'account' as const};
const out: Record<string, unknown> = {};
async function reset(){ await replaceDemoAccount(db,scope.accountId,'disposable-local-user'); }
async function events(){return (await db.select().from(schema.busEvents).where(eq(schema.busEvents.accountId,scope.accountId))).filter(e=>/^e\d+$/.test(e.id));}
async function mandates(){return db.select().from(schema.mandates).where(eq(schema.mandates.accountId,scope.accountId));}
try {
 await reset();
 const kernel = new Kernel(createRepositories(db));
 const before = await readOverview(db,scope);
 assert.equal(before.tiles[4]?.value,'331');
 assert.equal(before.bars.length,14);
 await kernel.decide(scope,'ap1',true);
 await kernel.decide(scope,'ap1',true);
 await kernel.decide(scope,'ap1',false);
 const approved = await readOverview(db,scope);
 assert.equal(approved.tiles[4]?.value,'332');
 assert.equal(approved.count,3);
 assert.equal((await events()).length,1);
 assert.equal((await mandates()).length,1);
 out.approve = {tasksBefore:before.tiles[4]?.value,tasksAfter:approved.tiles[4]?.value,count:approved.count,support:approved.agents.find(a=>a.id==='support'),events:await events(),mandates:await mandates()};
 const marketingBefore = approved.agents.find(a=>a.id==='marketing');
 await kernel.decide(scope,'ap2',false);
 const declined = await readOverview(db,scope);
 assert.deepEqual(declined.agents.find(a=>a.id==='marketing'),marketingBefore);
 assert.equal((await mandates()).length,1);
 out.decline = {count:declined.count,marketingUnchanged:true,events:await events(),mandateCount:(await mandates()).length};
 await reset();
 await db.delete(schema.stateEntries).where(and(eq(schema.stateEntries.accountId,scope.accountId),eq(schema.stateEntries.key,'policy.refund_auto_limit')));
 await assert.rejects(()=>kernel.decide(scope,'ap1',true));
 assert.equal((await readOverview(db,scope)).tiles[4]?.value,'331');
 assert.equal((await events()).length,0);
 assert.equal((await mandates()).length,0);
 out.missingLimit = {pendingCount:(await readOverview(db,scope)).count,tasks:'331',events:await events(),mandates:await mandates()};
 await reset();
 await db.delete(schema.rules).where(and(eq(schema.rules.accountId,scope.accountId),eq(schema.rules.agent,'support')));
 await assert.rejects(()=>kernel.decide(scope,'ap1',true));
 assert.equal((await readOverview(db,scope)).count,4);
 assert.equal((await events()).length,0);
 out.missingRule = {pendingCount:4,events:await events(),mandates:await mandates()};
 await reset();
 await kernel.decideMission(scope,'mp-inventory',true);
 await kernel.decideMission(scope,'mp-inventory',true);
 const mission = await readOverview(db,scope);
 assert.equal(mission.proposals.length,0);
 assert.equal(mission.agents.find(a=>a.id==='inventory')?.contribution,0);
 assert.equal(mission.tiles[4]?.value,'331');
 assert.equal((await events()).length,0);
 out.mission = {inventory:mission.agents.find(a=>a.id==='inventory'),count:mission.count,events:await events()};
 for (const id of ['ap1','ap2','ap3']) await kernel.decide(scope,id,false);
 const empty=await readOverview(db,scope);
 assert.equal(empty.empty,true);
 out.empty={count:empty.count,emptyText:empty.emptyText};
 await reset();
 await kernel.decideMission(scope,'mp-inventory',false);
 for (const id of ['ap1','ap2','ap3']) await kernel.decide(scope,id,false);
 const revising=await readOverview(db,scope);
 assert.equal(revising.empty,false);
 assert.equal(revising.proposals[0]?.revising,true);
 assert.equal(revising.count,0);
 out.revising={count:revising.count,empty:revising.empty,proposals:revising.proposals};
 await saveWorkspace(db,workspaceFromDesign());
 const noStore=await readOverview(db,{accountId:'leen',mode:'account'});
 assert.deepEqual(noStore.tiles.map(t=>t.value),['—','—','—','—','0','—']);
 out.noStore={tiles:noStore.tiles,bars:noStore.bars,empty:noStore.empty};
 writeFileSync('/Users/moeghashim/.no-mistakes/evidence/01M6E90HCJ2TVF0P0ZWYPHKXJ1/policy-runtime.json',JSON.stringify(out,null,2));
 console.log('Real Kernel and repository commands completed; persisted Approval, Mandate, event, mission, rollback, and loader results recorded in policy-runtime.json. No browser session was used.');
} finally {await opened.close();}
