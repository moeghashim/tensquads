import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
const evidence = '/Users/moeghashim/.no-mistakes/evidence/01M6VM556ZWGJ3457K52WHQWKH';
const base = 'http://127.0.0.1:8798';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const log = [];
const errors = [];
page.on('pageerror', e => errors.push(String(e)));
try {
  assert.equal((await page.goto(base+'/review')).status(),200);
  await page.getByRole('link',{name:/^Agent flow/}).click();
  await page.waitForURL(base+'/review/agent-flow');
  await page.getByRole('heading',{name:'How the tensquads agents work together'}).waitFor();
  await page.screenshot({path:evidence+'/agent-flow-desktop.png',fullPage:true});
  log.push('PASS: Open /review, click Agent flow, and see the flow page at /review/agent-flow.');
  const response = await page.goto(base+'/review/agent-flow?shared=1');
  assert.equal(response.status(),200);
  assert.match(response.headers()['content-type'],/text\/html/);
  assert.equal(response.headers()['x-robots-tag'],'noindex, nofollow');
  assert.equal(response.headers()['cache-control'],'no-cache');
  await page.reload();
  await page.getByRole('heading',{name:'How the tensquads agents work together'}).waitFor();
  const groups = await page.locator('svg g').allTextContents();
  for (const title of ['Research check','Brief']) assert(groups.some(t=>t.startsWith(title)&&t.includes('Fails twice')));
  for (const title of ['Preview check','Live page check']) assert(groups.some(t=>t.startsWith(title)&&t.endsWith('Fails')&&!t.includes('Fails twice')));
  assert.equal(await page.locator('figcaption').innerText(),'The flow for one business, as the system runs today. The research check gives Machu one more try. The preview and live-page checks share one retry for Angkor. The brief gets one rewrite. After that, a failure stops the run and tells the owner why.');
  for (const name of ['Petra','Machu','Angkor']) assert(await page.getByRole('heading',{name,exact:true}).isVisible());
  assert.equal(await page.getByRole('img',{name:/The tensquads agent flow/}).count(),1);
  await page.locator('.canvas').screenshot({path:evidence+'/agent-flow-diagram.png'});
  log.push('PASS: Direct shared URL and reload return HTTP 200 HTML, noindex/nofollow and no-cache. Rendered chart shows the approved retry labels and caption, plus all three role cards.');
  await page.getByRole('link',{name:'Back to review',exact:true}).click();
  await page.waitForURL(base+'/review/');
  assert(await page.getByRole('link',{name:/^Agent flow/}).isVisible());
  await page.screenshot({path:evidence+'/review-index.png',fullPage:true});
  log.push('PASS: Back to review returns to /review/ with the Agent flow card available.');
  await page.setViewportSize({width:390,height:844});
  await page.goto(base+'/review/agent-flow');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
  const canvas=page.locator('.canvas');
  assert(await canvas.evaluate(e=>e.scrollWidth>e.clientWidth));
  await page.screenshot({path:evidence+'/agent-flow-mobile.png',fullPage:true});
  await canvas.hover();
  await page.mouse.wheel(1200,0);
  await page.waitForTimeout(300);
  assert(await canvas.evaluate(e=>e.scrollLeft>0));
  await canvas.screenshot({path:evidence+'/agent-flow-mobile-scrolled.png'});
  log.push('PASS: At 390px the document has no horizontal overflow. The diagram scrolls horizontally by mouse wheel so its right-side decisions can be reached.');
  assert.deepEqual(errors,[]);
  log.push('No browser JavaScript errors.');
} finally {
  writeFileSync(evidence+'/live-checks.txt',log.join('\n')+'\n');
  await browser.close();
}
console.log(log.join('\n'));
